package String_Practice;

public class VowelConsonant {
    public static void main(String[] args) {
        char ch = 'Z';
        if (ch == 'a' || ch == 'e' || ch == 'i'|| ch == 'o'||ch == 'u'){
            System.out.println(" this is  a vowel: "+ ch);
        }
        else {
            System.out.println(" This is consonant : "+ ch);
        }

    }


}
